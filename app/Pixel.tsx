export default function Pixel({
  name,
  size = 20,
  tone = "#ff799b",
  ink = "#50354c",
}: {
  name: string;
  size?: number;
  tone?: string;
  ink?: string;
}) {
  const rows = shapes[name] || shapes.heart;
  return (
    <svg
      aria-hidden="true"
      width={size}
      height={size}
      viewBox={`0 0 ${rows[0].length} ${rows.length}`}
      shapeRendering="crispEdges"
    >
      {rows.flatMap((row, y) =>
        Array.from(row, (v, x) =>
          v === "0" ? null : (
            <rect
              key={x + "-" + y}
              x={x}
              y={y}
              width="1"
              height="1"
              fill={v === "1" ? ink : v === "2" ? tone : "#fff1c8"}
            />
          ),
        ),
      )}
    </svg>
  );
}
